import prisma from "@/features/shared/lib/prisma";
import { logger } from "@/features/shared/lib/logger";

const UPCOMING_STATUSES = new Set(["OPEN", "FULL"]);
const PAID_METHODS = new Set(["BDT", "MOBILE_PAYMENT", "BINANCE", "CARD"]);
const VES_RATE = Number(process.env.VES_RATE || process.env.NEXT_PUBLIC_VES_RATE || 0);

const REFERENCE_PREFIX = {
  BDT: "BDT",
  MOBILE_PAYMENT: "PM",
  BINANCE: "BNB",
  CARD: "CARD",
  STAFF_BYPASS: "STAFF",
  SUBSCRIPTION_CREDIT: "PASS",
};

function buildReference(method) {
  const prefix = REFERENCE_PREFIX[method] || "PAY";
  return `${prefix}-${Date.now().toString(36).toUpperCase()}-${Math.random()
    .toString(36)
    .slice(2, 6)
    .toUpperCase()}`;
}

function vesAmount(amount) {
  if (!Number.isFinite(VES_RATE) || VES_RATE <= 0) return null;
  return Math.round(Number(amount || 0) * VES_RATE * 100) / 100;
}

function isPast(date) {
  return new Date(date).getTime() < Date.now();
}

function isRetryable(error) {
  return error?.code === "P2034";
}

async function withRetry(operation, attempts = 3) {
  let lastError;
  for (let attempt = 0; attempt < attempts; attempt++) {
    try {
      return await operation();
    } catch (error) {
      lastError = error;
      if (!isRetryable(error)) throw error;
      logger.warn("Retrying serializable enrollment transaction", { attempt: attempt + 1 });
    }
  }
  throw lastError;
}

/**
 * Enrollment mutations live here because they touch three aggregates:
 * match capacity, participant row and subscription balance.
 */
export const matchEnrollmentRepository = {
  /**
   * Enrolls a player atomically.
   *
   * @param {Object} options
   * @param {string} options.matchId
   * @param {string} options.userId
   * @param {string|null} [options.paymentMethod] - BDT | MOBILE_PAYMENT | BINANCE | CARD | SUBSCRIPTION_CREDIT | STAFF_BYPASS
   * @param {string|null} [options.reference] - Reference supplied by the player or generated by the gateway.
   * @param {boolean} [options.staffBypass] - Verified by the action before reaching this layer.
   */
  async enroll({
    matchId,
    userId,
    paymentMethod = null,
    reference = null,
    staffBypass = false,
  }) {
    return withRetry(() =>
      prisma.$transaction(
        async (tx) => {
          const match = await tx.match.findFirst({
            where: { id: matchId, deletedAt: null },
            select: {
              id: true,
              title: true,
              status: true,
              scheduledAt: true,
              capacity: true,
              allowSubscription: true,
              pricePerSlot: true,
              court: { select: { isActive: true, deletedAt: true } },
              participants: { select: { userId: true, status: true } },
            },
          });

          if (!match) {
            return { success: false, error: "El partido no existe." };
          }
          if (!match.court || match.court.deletedAt || !match.court.isActive) {
            return { success: false, error: "La cancha no está disponible." };
          }
          if (!UPCOMING_STATUSES.has(match.status)) {
            return { success: false, error: "Este partido ya no acepta inscripciones." };
          }
          if (isPast(match.scheduledAt)) {
            return { success: false, error: "Este partido ya pasó." };
          }
          if (match.participants.some((participant) => participant.userId === userId)) {
            return { success: false, error: "Ya estás inscrito en este partido." };
          }

          const confirmedCount = match.participants.filter(
            (participant) => participant.status === "CONFIRMED"
          ).length;
          const status = confirmedCount < match.capacity ? "CONFIRMED" : "WAITLIST";

          // Waitlist spots never require payment: the player only pays if a
          // confirmed seat is eventually assigned.
          if (status === "WAITLIST") {
            await tx.participant.create({
              data: {
                userId,
                matchId,
                status,
                paymentType: "PAY_PER_MATCH",
                position: null,
              },
            });

            return {
              success: true,
              status,
              paymentType: "PAY_PER_MATCH",
              usedPass: false,
              paymentStatus: "WAITLIST",
              reference: null,
              slotsLeft: 0,
              message: "Partido lleno: quedaste en la lista de espera.",
            };
          }

          let paymentType = "PAY_PER_MATCH";
          let usedPass = false;
          let transaction = null;
          let transactionStatus = null;

          if (staffBypass) {
            transactionStatus = "COMPLETED";
          } else if (paymentMethod === "SUBSCRIPTION_CREDIT" || !paymentMethod) {
            // Backwards-compatible path for the old join button: use an active
            // pass when available. Explicit payment methods always charge.
            const subscription = match.allowSubscription
              ? await tx.userSubscription.findFirst({
                  where: {
                    userId,
                    isActive: true,
                    deletedAt: null,
                    remainingMatches: { gt: 0 },
                    endDate: { gte: new Date() },
                  },
                  orderBy: { endDate: "asc" },
                  select: { id: true, remainingMatches: true },
                })
              : null;

            if (subscription) {
              paymentType = "SUBSCRIPTION_CREDIT";
              usedPass = true;
              const nextRemaining = subscription.remainingMatches - 1;
              await tx.userSubscription.update({
                where: { id: subscription.id },
                data: {
                  remainingMatches: nextRemaining,
                  ...(nextRemaining <= 0 ? { isActive: false } : {}),
                },
              });
              transactionStatus = "COMPLETED";
            } else if (paymentMethod === "SUBSCRIPTION_CREDIT") {
              return {
                success: false,
                error: "No tienes un pase activo con créditos disponibles.",
                errorCode: "NO_ACTIVE_PASS",
              };
            } else {
              return {
                success: false,
                error: "Selecciona un método de pago para confirmar tu cupo.",
                errorCode: "PAYMENT_REQUIRED",
              };
            }
          } else if (PAID_METHODS.has(paymentMethod)) {
            transactionStatus = "PENDING";
          } else {
            return {
              success: false,
              error: "Método de pago no válido.",
              errorCode: "INVALID_PAYMENT_METHOD",
            };
          }

          await tx.participant.create({
            data: {
              userId,
              matchId,
              status,
              paymentType,
              position: null,
            },
          });

          // Record every confirmed seat that has a monetary or pass
          // implication. Staff bypass and pass usage are completed instantly;
          // external gateways stay pending until their webhook confirms them.
          if (transactionStatus) {
            const resolvedMethod = staffBypass
              ? "STAFF_BYPASS"
              : usedPass
                ? "SUBSCRIPTION_CREDIT"
                : paymentMethod;
            const resolvedReference =
              reference?.trim() || buildReference(resolvedMethod);
            const amount = usedPass ? 0 : Number(match.pricePerSlot || 0);

            transaction = await tx.transaction.create({
              data: {
                userId,
                matchId,
                amount,
                amountVes: vesAmount(amount),
                currency: "USD",
                type: usedPass ? "SUBSCRIPTION_CREDIT" : "PAY_PER_MATCH",
                method: resolvedMethod,
                status: transactionStatus,
                reference: resolvedReference,
                metadata: {
                  source: "public_checkout",
                  matchTitle: match.title,
                },
              },
              select: {
                id: true,
                status: true,
                method: true,
                reference: true,
                amount: true,
                amountVes: true,
                currency: true,
              },
            });
          }

          const nextConfirmed = confirmedCount + 1;
          await tx.match.update({
            where: { id: match.id },
            data: { status: nextConfirmed >= match.capacity ? "FULL" : "OPEN" },
          });

          return {
            success: true,
            status,
            paymentType,
            usedPass,
            paymentStatus: usedPass ? "COMPLETED" : transactionStatus,
            transaction,
            reference: transaction?.reference || null,
            slotsLeft: Math.max(0, match.capacity - nextConfirmed),
            message:
              transactionStatus === "PENDING"
                ? "Reserva confirmada. Tu pago quedó pendiente de validación."
                : usedPass
                  ? "¡Inscripción confirmada con tu pase!"
                  : "¡Inscripción confirmada! Nos vemos en la cancha.",
          };
        },
        { isolationLevel: "Serializable" }
      )
    );
  },

  async leave({ matchId, userId }) {
    return withRetry(() =>
      prisma.$transaction(
        async (tx) => {
          const match = await tx.match.findFirst({
            where: { id: matchId, deletedAt: null },
            select: {
              id: true,
              status: true,
              capacity: true,
              scheduledAt: true,
            },
          });

          if (!match) {
            return { success: false, error: "El partido no existe." };
          }
          if (isPast(match.scheduledAt) || match.status === "COMPLETED") {
            return { success: false, error: "No puedes cancelar un partido que ya pasó." };
          }

          const participant = await tx.participant.findUnique({
            where: { userId_matchId: { userId, matchId } },
            select: { id: true, status: true, paymentType: true },
          });

          if (!participant) {
            return { success: false, error: "No estás inscrito en este partido." };
          }

          await tx.participant.delete({ where: { id: participant.id } });

          if (participant.status === "CONFIRMED" && participant.paymentType === "SUBSCRIPTION_CREDIT") {
            const subscription = await tx.userSubscription.findFirst({
              where: { userId, deletedAt: null, endDate: { gte: new Date() } },
              orderBy: { endDate: "desc" },
              select: { id: true, remainingMatches: true },
            });

            if (subscription) {
              await tx.userSubscription.update({
                where: { id: subscription.id },
                data: {
                  remainingMatches: subscription.remainingMatches + 1,
                  isActive: true,
                },
              });
            }
          }

          let promoted = false;
          if (participant.status === "CONFIRMED") {
            const next = await tx.participant.findFirst({
              where: { matchId, status: "WAITLIST" },
              orderBy: { createdAt: "asc" },
              select: { id: true },
            });

            if (next) {
              await tx.participant.update({
                where: { id: next.id },
                data: { status: "CONFIRMED" },
              });
              promoted = true;
            }
          }

          const confirmedCount = await tx.participant.count({
            where: { matchId, status: "CONFIRMED" },
          });

          await tx.match.update({
            where: { id: match.id },
            data: {
              status:
                confirmedCount >= match.capacity
                  ? "FULL"
                  : match.status === "FULL"
                    ? "OPEN"
                    : match.status,
            },
          });

          return {
            success: true,
            promoted,
            message: promoted
              ? "Inscripción cancelada. Un jugador de la lista de espera tomó tu cupo."
              : "Inscripción cancelada.",
          };
        },
        { isolationLevel: "Serializable" }
      )
    );
  },
};
